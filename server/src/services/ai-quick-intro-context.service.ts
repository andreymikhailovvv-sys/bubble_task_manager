/**
 * Immediate, context-aware progress text for the period before the optional
 * cheap AI model answers. This code MUST NOT imply that data has already been
 * read, changed or sent. It only describes the next step.
 */
export function buildContextualAiIntro(question: string, context: string): string {
  const request = question.trim().toLocaleLowerCase('ru');
  const area = context.toLocaleLowerCase('ru');
  const contains = (pattern: RegExp) => pattern.test(request);
  const sector = question.match(/сектор(?:а|е|у|ом)?\s+[«"']?([\p{L}\p{N}-]{2,25})/iu)?.[1];
  const sectorDetail = sector ? ' в секторе «' + sector + '»' : '';
  const mailService = /яндекс/iu.test(request) ? ' Яндекс Почты' : /mail\.ru/iu.test(request) ? ' Mail.ru' : '';

  if (contains(/почт|письм|email|e-mail|mail\.ru|яндекс.*почт|входящ/iu)) {
    if (contains(/ответ|отправ|напис|состав|черновик/iu)) {
      return 'Посмотрю контекст переписки и подберу формулировку ответа на письмо.';
    }
    if (contains(/непрочит|новы|входящ|сегодня|последн/iu)) {
      return 'Проверю свежие письма' + mailService + ' и выделю важные сообщения.';
    }
    if (contains(/найд|поиск|от кого|отправител|тем[ыуе]/iu)) {
      return 'Поищу нужные письма и сверю отправителей с содержанием.';
    }
    return 'Посмотрю письма по вашему вопросу и соберу нужные сведения.';
  }
  if (contains(/задач|дела\b|дедлайн|просроч|сектор|подзадач|to.?do/iu) || /помощь ии по задач/iu.test(area)) {
    if (contains(/просроч|не выполн|дедлайн|опозд/iu)) {
      return 'Проверю сроки задач' + sectorDetail + ' и отмечу то, что требует внимания.';
    }
    if (contains(/завтра|сегодня|недел|выходн|расписан|календар/iu)) {
      return 'Сверю задачи с нужными датами и соберу удобную картину дня.';
    }
    if (contains(/созда|добав|постав|запланир|напомни/iu)) {
      return 'Уточню параметры новой задачи и подготовлю её к добавлению.';
    }
    if (contains(/приорит|важн|очеред|сортир/iu)) {
      return 'Сопоставлю задачи по срокам и важности, чтобы выделить приоритеты.';
    }
    return 'Посмотрю задачи' + sectorDetail + ' и выделю нужные детали.';
  }
  if (contains(/привычк|повторен|регулярн/iu)) {
    return 'Разберу расписание повторения и подберу настройки привычки.';
  }
  if (contains(/уведомлен|напомни|напоминан|триггер/iu)) {
    return 'Уточню условие и время напоминания, чтобы не пропустить нужный момент.';
  }
  if (contains(/сводк|резюм|кратк|итог|суммари|подытож/iu)) {
    return 'Выделю основные факты и соберу краткую, понятную сводку.';
  }
  if (contains(/план|поэтап|шаг|стратег|организ/iu)) {
    return 'Разложу задачу на последовательные шаги и отмечу приоритеты.';
  }
  if (contains(/напис|состав|сформулир|текст|письмо|сообщен|пост|перефразир|редактир/iu)) {
    if (contains(/абзац|структур|оформ|форматир/iu)) {
      return 'Сначала выстрою структуру текста, затем аккуратно оформлю абзацы.';
    }
    return 'Подберу формулировки, тон и структуру текста под вашу задачу.';
  }
  if (contains(/сравн|сопостав|выбор|какой лучше|вариант/iu)) {
    return 'Сопоставлю варианты по ключевым критериям и объясню различия.';
  }
  if (contains(/файл|документ|pdf|таблиц|excel|отч[её]т/iu)) {
    return 'Проверю, какие данные нужны из документа, и подготовлю разбор.';
  }
  if (contains(/перевед|перевод|translate/iu)) {
    return 'Учту смысл и стиль исходного текста при переводе.';
  }
  if (contains(/поищ|найд|проверь|узнай|посмотри/iu)) {
    return 'Определю, где искать нужные сведения, и проверю результаты.';
  }
  if (contains(/объясни|почему|как работает|что такое/iu)) {
    return 'Разберу суть вопроса и объясню её на понятных примерах.';
  }
  if (/корпоративн|диспетчер|компан|work/iu.test(area)) {
    return 'Уточню рабочий контекст и сверю детали, важные для команды.';
  }
  const topic = question
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/^[\s.,!?;:]+|[\s.,!?;:]+$/g, '')
    .slice(0, 62).trim();
  return topic.length > 4
    ? 'Разберусь с темой «' + topic + (question.trim().length > 62 ? '…' : '') + '» и выделю главное.'
    : 'Уточню суть вопроса и выберу подходящий способ ответа.';
}
